namespace Fuxion.Tool.Test;

/// <summary>
/// The views (plan U, U4 step 6b; the SPEC of the module, 5.4): generated from their recipe, the same bytes for the same
/// catalog, in the language of <c>docs.yaml</c>; <c>fx doctor</c> says when one is out of date, and <c>fx sync</c>
/// regenerates it, never over an edit by hand without <c>--adopt</c>.
/// </summary>
public sealed class DocsViewsTest
{
	const string Actors = "schema: 1.0.0\nactors: [editor]\n";
	static readonly DateTimeOffset Now = DocsCheckTest.At.AddDays(1);

	static Func<string, string> Display(Space space) => p => FxLayout.Relative(space.Root, p);

	static DocFile File(Space space, string path) => space.Catalog().Files.Single(f => f.Path == path);

	static string View(Space space, string title, string profile, string recipe, string scope, string? folder = null)
	{
		var change = DocEditor.New(space.Catalog(), Display(space), space.Root, "view", title, null, profile, folder, [], "editor", DocsCheckTest.At, new(recipe, scope));
		Assert.True(change.Write(), string.Join("; ", change.Diagnostics.Select(d => $"{d.Code} {d.Message.English}")));
		return change.Documents.Single();
	}

	static Space Catalog(string docs = Actors)
	{
		var space = new Space(docs);
		space.Add("adr", "open-one");
		space.Add("adr", "accepted-one", status: "accepted");
		space.Add("plan", "blocked-one", status: "blocked");
		space.Add("plan", "done", status: "completed");
		space.Add("design", "the-design", folder: "notes", status: "active", tags: ["mcp"]);
		return space;
	}

	[Fact(DisplayName = "docs.status: what asks for attention, what is open and what is in force, by type; the closed ones and the views, not")]
	public void Status()
	{
		using var space = Catalog();
		var view = View(space, "Status", "status", DocRecipes.Status, "_docs");
		Assert.Equal("""
			# Status

			> Generated by fx sync (recipe `docs.status`, scope `_docs`): it is not edited by hand.

			1 open · 2 in force · 1 asking for attention · 5 documents.

			## Asking for attention

			### plan

			- [The blocked-one](_records/2026/10/PLAN-blocked-one.md) · `blocked` · 2026-10-21

			## Open

			### adr

			- [The open-one](_records/2026/10/ADR-open-one.md) · `draft` · 2026-10-21

			## In force

			### adr

			- [The accepted-one](_records/2026/10/ADR-accepted-one.md) · `accepted` · 2026-10-21

			### design

			- [The the-design](notes/DESIGN-the-design.md) · `active` · 2026-10-21

			""".Replace("\r\n", "\n"), space.Read($"_docs/{view}"));
		Assert.Empty(space.Problems());
	}

	[Fact(DisplayName = "the language of the views is that of docs.yaml, whoever runs fx")]
	public void Language()
	{
		using var space = Catalog("schema: 1.0.0\nactors: [editor]\nlanguage: es\n");
		var view = View(space, "Estado", "status", DocRecipes.Status, "_docs");
		Assert.Contains("## Piden atención", space.Read($"_docs/{view}"));
		Assert.Contains("1 abiertos · 2 vigentes · 1 piden atención · 5 documentos.", space.Read($"_docs/{view}"));
		Assert.Equal(DocsYamlReader.InvalidYaml, Assert.Throws<DocsConfigException>(() => DocsYamlReader.Read("schema: 1.0.0\nlanguage: fr\n", "docs.yaml")).Diagnostics[0].Code);
	}

	[Fact(DisplayName = "docs.catalog: the documents of a folder in a table; docs.catalog/<tag>, those with the tag")]
	public void CatalogView()
	{
		using var space = Catalog();
		var records = View(space, "Records", "catalog", DocRecipes.Catalog, "_docs/_records", folder: "notes");
		var text = space.Read($"_docs/{records}");
		Assert.Contains("| Document | Type | Status | Updated |\n|---|---|---|---|\n| [The accepted-one](../_records/2026/10/ADR-accepted-one.md) | adr | `accepted` | 2026-10-21 |", text);
		Assert.Equal(4, text.Split('\n').Count(l => l.StartsWith("| [", StringComparison.Ordinal)));
		var tagged = space.Read($"_docs/{View(space, "MCP", "catalog", $"{DocRecipes.Catalog}/mcp", "_docs")}");
		Assert.Contains("| [The the-design](notes/DESIGN-the-design.md) | design | `active` | 2026-10-21 |", tagged);
		Assert.Single(tagged.Split('\n'), l => l.StartsWith("| [", StringComparison.Ordinal));
		Assert.Empty(space.Problems());
	}

	[Fact(DisplayName = "docs.backlog: the open entries of a register by status, in the order of their keys, with their fields and documents; then the closed")]
	public void Backlog()
	{
		using var space = new Space(Actors);
		var register = space.Add("register", "ideas", folder: "ideas");
		var research = space.Add("research", "faces");
		DocChange Add(string title, DocEntryEdit edit) => DocEditor.AddEntry(space.Catalog(), Display(space), space.Root, File(space, register), title, edit, Now);
		Assert.True(Add("Diez", new() { Key = "I-10", Status = "backlog", Fields = [new("prioridad", JsonValue("1"))], Relations = [("related-to", research)] }).Write());
		Assert.True(Add("Dos", new() { Key = "I-2", Status = "backlog", Fields = [new("bloque", JsonValue("\"Hub\"")), new("espera", JsonValue("[\"I-1\"]"))] }).Write());
		Assert.True(Add("Sin clave", new() { Status = "boceto" }).Write());
		Assert.True(Add("Uno", new() { Key = "I-1" }).Write());
		Assert.True(DocEditor.CloseEntry(space.Catalog(), Display(space), File(space, register), "I-1", "hecha", Now).Write());
		var text = space.Read($"_docs/{View(space, "Ideas board", "catalog", DocRecipes.Backlog, $"_docs/{register}", folder: "ideas")}");
		Assert.Contains("3 open · 1 closed.", text);
		Assert.Contains("""
			## backlog

			| Entry | Title | Fields | Documents |
			|---|---|---|---|
			| I-2 | Dos | bloque: Hub · espera: I-1 |  |
			| I-10 | Diez | prioridad: 1 | [The faces](../_records/2026/10/RESEARCH-faces.md) |

			## boceto
			""".Replace("\r\n", "\n"), text);
		Assert.Contains("| sin-clave | Sin clave |  |  |", text);
		Assert.Contains("## Closed\n\n| Entry | Title | Status | Closed |\n|---|---|---|---|\n| I-1 | Uno | `hecha` | 2026-10-22 |\n", text);
		Assert.Empty(space.Problems());
	}

	static System.Text.Json.JsonElement? JsonValue(string json)
	{
		using var document = System.Text.Json.JsonDocument.Parse(json);
		return document.RootElement.Clone();
	}

	[Theory(DisplayName = "a view without a valid recipe or scope: an error, and new does not make it")]
	[InlineData("docs.timeline", "_docs", DocViews.UnknownRecipe)]
	[InlineData("docs.status", "_docs/nowhere", DocViews.InvalidScope)]
	[InlineData("docs.status", "elsewhere", DocViews.InvalidScope)]
	[InlineData("docs.backlog", "_docs/notes/DESIGN-the-design.md", DocViews.InvalidScope)]
	public void InvalidView(string recipe, string scope, string code)
	{
		using var space = Catalog();
		Directory.CreateDirectory(space.Full("elsewhere"));
		var change = DocEditor.New(space.Catalog(), Display(space), space.Root, "view", "A view", null, "status", null, [], "editor", Now, new(recipe, scope));
		Assert.Equal(code, Assert.Single(change.Diagnostics).Code);
		var view = View(space, "Status", "status", DocRecipes.Status, "_docs");
		space.Change(view, s => s["generation"] = new System.Text.Json.Nodes.JsonObject { ["recipe"] = recipe, ["scope"] = scope });
		Assert.Contains(code, space.Problems().Select(p => p.Code));
	}

	[Fact(DisplayName = "fx doctor says a view is out of date; fx sync makes it again, and again gives the same bytes")]
	public void Sync()
	{
		using var space = Catalog();
		var view = View(space, "Status", "status", DocRecipes.Status, "_docs");
		var options = new SyncOptions(Offline: true, Skill: FxSkill.Text);
		FxModuleResult Docs(bool doctor, SyncOptions? with = null)
			=> (doctor ? SyncEngine.Doctor(space.Root, with ?? options, cancellationToken: TestContext.Current.CancellationToken)
				: SyncEngine.Sync(space.Root, with ?? options, cancellationToken: TestContext.Current.CancellationToken)).Single(r => r.Module == DocsModule.Name);
		Assert.Empty(Docs(doctor: true).Diagnostics);
		space.Add("rfc", "new-one");
		Assert.Equal((DocViews.ViewOutdated, $"_docs/{view}"), Docs(doctor: true).Diagnostics.Select(d => (d.Code, d.File)).Single());
		var sync = Docs(doctor: false);
		Assert.Equal([SyncFileStatus.Written, SyncFileStatus.Written], sync.Files.Select(f => f.Status));
		Assert.Contains("The new-one", space.Read($"_docs/{view}"));
		Assert.Empty(Docs(doctor: true).Diagnostics);
		var bytes = System.IO.File.ReadAllBytes(space.Full($"_docs/{view}"));
		var sidecar = space.Read($"_docs/{Space.Sidecar(view)}");
		Assert.Equal(SyncFileStatus.Unchanged, Assert.Single(Docs(doctor: false).Files).Status);
		Assert.Equal(bytes, System.IO.File.ReadAllBytes(space.Full($"_docs/{view}")));
		Assert.Equal(sidecar, space.Read($"_docs/{Space.Sidecar(view)}"));
	}

	[Fact(DisplayName = "fx sync does not replace a view edited by hand, unless --adopt")]
	public void SyncEdited()
	{
		using var space = Catalog();
		var view = View(space, "Status", "status", DocRecipes.Status, "_docs");
		System.IO.File.AppendAllText(space.Full($"_docs/{view}"), "Mine.\n");
		var options = new SyncOptions(Offline: true, Skill: FxSkill.Text);
		var refused = SyncEngine.Sync(space.Root, options, cancellationToken: TestContext.Current.CancellationToken).Single(r => r.Module == DocsModule.Name);
		Assert.Equal((SyncFileStatus.Refused, DocChecker.ViewEdited), (Assert.Single(refused.Files).Status, Assert.Single(refused.Diagnostics).Code));
		Assert.EndsWith("Mine.\n", space.Read($"_docs/{view}"));
		SyncEngine.Sync(space.Root, options with { Adopt = true }, cancellationToken: TestContext.Current.CancellationToken);
		Assert.DoesNotContain("Mine.", space.Read($"_docs/{view}"));
		Assert.Empty(space.Problems());
	}

	[Fact(DisplayName = "fx doc new view --recipe --scope: the view, already generated")]
	public void Cli()
	{
		using var space = Catalog();
		var (exitCode, _, _) = DocsCheckTest.Fx(space.Root, "doc", "new", "view", "Status", "--profile", "status", "--recipe", "docs.status", "--actor", "editor");
		Assert.Equal(0, exitCode);
		Assert.Contains("## Asking for attention", space.Read("_docs/VIEW-status.md"));
		Assert.Equal(1, DocsCheckTest.Fx(space.Root, "doc", "new", "view", "Other", "--profile", "status", "--actor", "editor").ExitCode);
		Assert.True(DocsCheckTest.Json(space.Root, "fx-doc-check/1", "doc", "check").GetProperty("ok").GetBoolean());
	}
}
