using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using Fuxion.Tool.Core.Layout;
using Fuxion.Tool.Core.Mounts;
using Fuxion.Tool.Core.Results;
using Fuxion.Tool.Core.Worktree;

namespace Fuxion.Tool.Core.Explore;

/// <summary>What a node of the tree of <c>fx ui</c> is (plan O, decision 14).</summary>
public enum FxTreeKind
{
	/// <summary>A space on disk that mounts others: the root, or one mounted.</summary>
	Space,

	/// <summary>A repository mounted, at its place.</summary>
	Repository,

	/// <summary>Declared and not on disk: not mounted, or mounted and not cloned yet ("fantasma", 14.1).</summary>
	Declared,

	/// <summary>Declared, with its clone in the parking.</summary>
	Parked,

	/// <summary>On disk and nobody declares it ("?"): a repository, or a folder the workspace does not version.</summary>
	Unknown,

	Folder,

	File,

	/// <summary>A module of fx this root uses (its folder in <c>_fx/</c>), on or off (<c>enabled: false</c>).</summary>
	Module,

	/// <summary>A module fx knows that this root does not use: shown dimmed (14.8).</summary>
	ModuleOff
}

/// <summary>Whose a file is (decision 14.3).</summary>
public enum FxOrigin
{
	/// <summary>Written by hand.</summary>
	Hand,

	/// <summary>Generated by fx: read-only, with its header.</summary>
	Generated,

	/// <summary>What the root receives from its workspace, in <c>_fx/.inherited/</c>.</summary>
	Inherited,

	/// <summary>A file a workspace gives it, outside <c>_fx/</c> (a share).</summary>
	Share,

	/// <summary>Local, not versioned (<c>~$</c>).</summary>
	Local
}

/// <summary>
/// A node of the tree of <c>fx ui</c>: what is on disk and what the manifests declare, in one tree (decision 14.1), with
/// what each node is, whose each file is, and the diagnostics of the doctor that are about it.
/// </summary>
public sealed class FxTreeNode
{
	readonly List<FxTreeNode> _children = [];

	public required FxTreeKind Kind { get; init; }

	public required string Name { get; init; }

	/// <summary>Full path, without a trailing separator.</summary>
	public required string Path { get; init; }

	public FxTreeNode? Parent { get; private set; }

	public IReadOnlyList<FxTreeNode> Children => _children;

	/// <summary>Of a repository or a workspace: who it is (its full name, its tags).</summary>
	public FxIdentity? Identity { get; init; }

	/// <summary>Of a repository: its declaration in the workspace that mounts it.</summary>
	public Mount? Declaration { get; init; }

	/// <summary>Of a repository: whether it is mounted (the intent of the developer, or required).</summary>
	public bool Mounted { get; init; }

	/// <summary>Of a repository: the copy used instead of this one, if a higher one supersedes it (plan P, decision 19).</summary>
	public RepositoryCopy? SupersededBy { get; init; }

	/// <summary>Of a repository: mounted as a guest, it inherits from its own parent (plan P, decision 18).</summary>
	public bool Guest => Declaration is { Inherits: false };

	/// <summary>Of a file (or a local folder): whose it is.</summary>
	public FxOrigin Origin { get; init; }

	/// <summary>Of an inherited file or a share: the workspaces it comes from.</summary>
	public IReadOnlyList<string> From { get; init; } = [];

	/// <summary>Of a module: whether it is on (its yaml does not say <c>enabled: false</c>).</summary>
	public bool Enabled { get; init; } = true;

	/// <summary>The rest of its content is on disk, not in the tree: what does not matter to fx (14.6). <see cref="FxTree.LoadMore"/>.</summary>
	public bool HasMore { get; internal set; }

	/// <summary>Of a workspace: its worktrees (14.12).</summary>
	public IReadOnlyList<WorktreeInfo> Worktrees { get; init; } = [];

	/// <summary>What the doctor found about it (14.2).</summary>
	public List<FxDiagnostic> Diagnostics { get; } = [];

	/// <summary>A repository or a workspace, on disk or not.</summary>
	public bool IsRepository => Declaration is not null || Identity is not null;

	internal FxTreeNode Add(FxTreeNode child)
	{
		child.Parent = this;
		_children.Add(child);
		return child;
	}

	internal void Sort()
	{
		static int Rank(FxTreeNode n) => n.Name == FxLayout.Folder ? 0 : n.Kind == FxTreeKind.File ? 2 : 1;
		_children.Sort((a, b) => Rank(a) != Rank(b) ? Rank(a).CompareTo(Rank(b)) : string.Compare(a.Name, b.Name, StringComparison.OrdinalIgnoreCase));
	}

	public IEnumerable<FxTreeNode> Descendants() => _children.SelectMany(c => c.Descendants().Prepend(c));

	/// <summary>The problems here and below (the <c>info</c> ones aside): what its mark counts.</summary>
	public int Problems => Descendants().Prepend(this).Sum(n => n.Diagnostics.Count(d => d.Severity != FxSeverity.Info));

	/// <summary>The worst problem here and below: its mark (✓ ! ✗), which goes up to its parents.</summary>
	public FxSeverity? Worst
		=> Descendants().Prepend(this).SelectMany(n => n.Diagnostics).Where(d => d.Severity != FxSeverity.Info)
			.Select(d => (FxSeverity?)d.Severity).OrderBy(s => s == FxSeverity.Error ? 0 : 1).FirstOrDefault();

	/// <summary>The deepest node that is <paramref name="path"/> or contains it.</summary>
	public FxTreeNode? Find(string path)
	{
		var full = System.IO.Path.TrimEndingDirectorySeparator(System.IO.Path.GetFullPath(path));
		if (!string.Equals(full, Path, StringComparison.OrdinalIgnoreCase)
		    && !full.StartsWith(Path + System.IO.Path.DirectorySeparatorChar, StringComparison.OrdinalIgnoreCase))
			return null;
		foreach (var child in _children)
			if (child.Find(full) is { } found)
				return found;
		return this;
	}

	public override string ToString() => $"{Kind} {Name}";
}
