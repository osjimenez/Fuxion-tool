using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using Fuxion.Tool.Core.Layout;

namespace Fuxion.Tool.Cli.Describe;

/// <summary>
/// The skill of fx for coding agents (plan O, O5): a <c>SKILL.md</c> made from what <c>fx describe</c> gives (decision
/// 12), so it never drifts from the commands: how an agent runs fx, every command with its arguments, options, output
/// and what it does, the global options and the exit codes. Always in English, as the JSON of fx.
/// </summary>
public static class FxSkill
{
	public const string Name = "fx";

	/// <summary>The skill, made once from the commands of this fx: what <c>fx sync</c> writes in every root of fx (plan O, O5.1).</summary>
	public static string Text => Made.Value;

	static readonly Lazy<string> Made = new(() => Render(DescribeCommand.Document(Directory.GetCurrentDirectory())));

	public static string Render(DescribeDocument document)
	{
		var b = new StringBuilder();
		b.Append("---\n");
		b.Append($"name: {Name}\n");
		b.Append("description: \"How to use fx, the tool of the Fuxion workspace (sync, doctor, mounts, worktrees, versions, the configuration in _fx/): ")
			.Append("every command with its options, its JSON output and whether it changes something. Use it before running fx; when a build fails because ")
			.Append("something generated is outdated; to park, unpark or pull mounts; to work on a branch apart (fx worktree); to change the rules ")
			.Append("or skills of the coding agents (AGENTS.md, CLAUDE.md, .claude/skills, all generated from _fx/harness/); or to read or change ")
			.Append("the configuration of the workspace.\"\n");
		b.Append("---\n\n");
		b.Append(FxHeader.Xml("the commands of fx (fx describe --skill)"));
		b.Append('\n');
		b.Append("# fx\n\n");
		b.Append("The tool of the Fuxion workspace: it generates what the repositories share from `_fx/` (`fx sync`), checks it (`fx doctor`), ")
			.Append("mounts and parks repositories, makes worktrees and versions from git. This skill is generated from `fx describe`: ")
			.Append("`fx describe --output json` has the same, as data.\n\n");

		b.Append("## How an agent runs fx\n\n");
		b.Append("- **Ask for JSON**: `--output json` writes one document on stdout (`schema`, `ok`, the data of the command and `diagnostics`, ")
			.Append("each with `code`, `severity`, `message`, `file`, `line` and `fix`). `fx schema <id>` gives the JSON Schema of each `fx-*/1`. ")
			.Append("`--output ndjson` writes events as the work goes on; the last line is the document.\n");
		b.Append("- **Nothing is asked without a person**: pass every value. A missing one ends with exit code 2 and says what is missing.\n");
		foreach (var interactive in document.Commands.Where(c => c.Interactive))
			b.Append($"- **Never `fx {interactive.Name}`**: it needs a person at a terminal (exit code 2 without one).\n");
		b.Append("- **Before changing, `--dry-run`** where a command takes it: it says what would change. The commands that edit the configuration ")
			.Append("also say what `fx sync` would do with the change.\n");
		b.Append("- **Never edit what fx generates** (files with the header `GENERATED by Fuxion.Tool (fx)`) nor `_fx/.inherited/`: change the ")
			.Append("yaml of the module in `_fx/` (or use the commands that edit it) and run `fx sync`. `fx doctor` checks without changing anything.\n");
		b.Append("- **To work on a branch apart, `fx worktree add <branch>`**, never `git worktree add`: fx puts it in its place, with the ")
			.Append("repositories it needs, and the build sees it as a closed tree. `fx worktree remove <branch>` when done.\n\n");

		b.Append("## The files of the coding agents (the harness)\n\n");
		b.Append("`AGENTS.md`, `CLAUDE.md`, `.claude/rules/`, `.claude/skills/` and `.agents/skills/` are generated by fx in every root of fx: ")
			.Append("never edit them, `fx sync` writes them again. Their source is `_fx/harness/`, and what the workspace gives in ")
			.Append("`_fx/.inherited/harness/`:\n\n");
		b.Append("- `_fx/harness/harness.yaml` lists the rules and the skills, each with its `applies-to` (tags or repositories; it decides for ")
			.Append("the root itself too; without it, for everyone) and, for a rule, its `paths`.\n");
		b.Append("- A rule is `_fx/harness/rules/<name>.md`, Markdown that starts with its `##` title. Without `paths` it goes into `AGENTS.md`; ")
			.Append("with them, into `.claude/rules/<name>.md`, and `AGENTS.md` says when to read it.\n");
		b.Append("- A skill is the folder `_fx/harness/skills/<name>/`: its `SKILL.md` (a front matter with `name: <name>` and a `description`) ")
			.Append("and whatever it needs, copied to `.claude/skills/` and `.agents/skills/`.\n");
		b.Append("- To change what the agents are told: write the rule or the skill there (in the workspace, for what is inherited), declare it ")
			.Append("in `harness.yaml` and run `fx sync`. `fx sync --adopt` moves into `_fx/harness/` what was written by hand in those files.\n");
		b.Append("- The rule and the skill named `fx` are fx's own: every root of fx gets them.\n\n");

		b.Append("## Commands\n\n");
		b.Append("| Command | What it does | JSON | Changes | Network | `--dry-run` |\n");
		b.Append("|---|---|---|---|---|---|\n");
		foreach (var c in document.Commands)
			b.Append($"| `fx {c.Name}` | {Cell(c.Description)} | {(c.Output is null ? "—" : $"`{c.Output}`")} | {Mark(c.Writes)} | {Mark(c.Network)} | {Mark(c.DryRun)} |\n");
		b.Append('\n');
		foreach (var c in document.Commands.Where(c => !c.Interactive))
		{
			b.Append($"### `fx {Usage(c)}`\n\n");
			b.Append($"{c.Description}\n\n");
			foreach (var argument in c.Arguments)
				b.Append($"- `<{argument.Name}>` ({Count(argument.Arity)}): {argument.Description}\n");
			foreach (var option in c.Options.Where(o => o.Name != "--help"))
				b.Append($"- {Option(option)}\n");
			if (c.Arguments.Count > 0 || c.Options.Any(o => o.Name != "--help"))
				b.Append('\n');
		}

		b.Append("## Global options\n\n");
		foreach (var option in document.GlobalOptions.Where(o => o.Name != "--help"))
			b.Append($"- {Option(option)}\n");
		b.Append('\n');
		b.Append("## Exit codes\n\n");
		foreach (var code in document.ExitCodes)
			b.Append($"- `{code.Code}`: {code.Meaning}\n");
		return b.ToString();
	}

	static string Mark(bool value) => value ? "yes" : "";

	static string Cell(string text) => text.Replace("|", "\\|").Replace("\n", " ");

	static string Count(string arity) => arity switch
	{
		"1" => "required",
		"0..1" => "optional",
		_ => arity.StartsWith('0') ? "any number" : "one or more"
	};

	static string Usage(JsonCommand command)
		=> string.Join(' ', command.Arguments.Select(a => a.Arity == "1" ? $"<{a.Name}>" : $"[<{a.Name}>{(a.Arity.EndsWith('*') ? "..." : "")}]").Prepend(command.Name));

	static string Option(JsonOption option)
	{
		var names = string.Join(", ", option.Aliases.Append(option.Name).Distinct().Select(n => $"`{n}`"));
		var type = option.Type == "bool" ? "" : $" <{option.Type}>";
		var values = option.Values is { Count: > 0 } ? $" ({string.Join(", ", option.Values.Select(v => $"`{v}`"))})" : "";
		return $"{names}{type}{values}{(option.Required ? " (required)" : "")}: {option.Description}";
	}
}
