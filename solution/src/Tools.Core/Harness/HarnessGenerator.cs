using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Fuxion.Tools.Core.Layout;
using Fuxion.Tools.Core.Yaml;

namespace Fuxion.Tools.Core.Harness;

/// <summary>
/// The files of the coding agents, from the rules and skills of a root (plan Q). Always in English, as everything fx
/// writes (proposal 11); the text of the rules is the user's.
/// </summary>
public static class HarnessGenerator
{
	/// <summary>The title of the rule of fx, the first of every <c>AGENTS.md</c> (decision 6).</summary>
	public const string FxRuleTitle = "## This repository and fx";

	public const string FxWorkspaceRuleTitle = "## This workspace and fx";

	/// <summary>
	/// The rule of fx (decision 6): who the root is, what is generated and must not be edited, where each thing is changed,
	/// and <c>fx worktree add</c> for another branch (plan P, decision 30). Only from what does not depend on the disk
	/// around it (its identity, what its workspace said in <c>inherited.yaml</c>), so a clone on its own generates the same.
	/// </summary>
	public static string FxRule(FxIdentity identity, bool workspace, FxInheritedParent? parent)
	{
		var b = new StringBuilder();
		b.Append(workspace ? FxWorkspaceRuleTitle : FxRuleTitle).Append("\n\n");
		var parentName = parent?.FullName.Split('/', StringSplitOptions.RemoveEmptyEntries).LastOrDefault();
		var url = parent?.Url is { Length: > 0 } u ? $" ({u})" : "";
		if (workspace)
			b.Append($"This is the workspace `{identity.Name}`")
				.Append(parent is null ? "." : $" (`{identity.FullName}`), inside the workspace `{parentName}`{url}.");
		else if (parent is not null)
			b.Append($"This is `{identity.Name}` (`{identity.FullName}`), a repository of the workspace `{parentName}`{url}.");
		else
			b.Append($"This is `{identity.Name}`, a repository with fx.");
		if (identity.Tags.Count > 0)
			b.Append(" Tags: ").Append(string.Join(", ", identity.Tags.Select(t => $"`{t}`"))).Append('.');
		b.Append('\n');
		if (workspace)
			b.Append("\nIts repositories are cloned inside it, each with its own git: `fx repo status` lists them and `fx sync` clones what is ")
				.Append("missing. Before a git command, find the repository the file belongs to and use `git -C <its folder>`.\n");
		b.Append("\nfx (Fuxion.Tools) manages its configuration, in `_fx/`; the skill `fx` says how to use it.\n\n");
		b.Append("- Never edit what fx generates: the files with the header `GENERATED by Fuxion.Tools (fx) - DO NOT EDIT`");
		b.Append(parent is null ? "" : ", and `_fx/.inherited/`, what its workspace gives it");
		b.Append(". Change their source in `_fx/`");
		b.Append(parent is null ? "" : " (the workspace's, for what is inherited)");
		b.Append(" and run `fx sync`; `fx doctor` checks everything without changing anything.\n");
		b.Append("- These files for coding agents (`AGENTS.md`, `CLAUDE.md`, `.claude/rules/`, `.claude/skills/`, `.agents/skills/`) are ")
			.Append("generated too, from the rules and skills of `_fx/harness/`")
			.Append(parent is null ? "" : " and `_fx/.inherited/harness/`")
			.Append(".\n");
		if (workspace || parent is not null)
			b.Append("- To work on another branch, `fx worktree add <branch>`").Append(workspace ? "" : " in the workspace")
				.Append(", never `git worktree add`.\n");
		return b.ToString();
	}

	/// <summary>
	/// <c>AGENTS.md</c> (proposal 4): the rule of fx, the rules that are always read (what is inherited first, then its
	/// own) and the index of the rules by path (decision 5).
	/// </summary>
	public static string Agents(string from, string fxRule, IEnumerable<(HarnessRule Rule, string Text)> rules)
	{
		var all = rules.ToList();
		var b = new StringBuilder(FxHeader.Xml(from));
		b.Append('\n').Append(fxRule);
		foreach (var (_, text) in all.Where(r => !r.Rule.ByPath))
			b.Append('\n').Append(Body(text));
		var byPath = all.Where(r => r.Rule.ByPath).Select(r => r.Rule).ToList();
		if (byPath.Count > 0)
		{
			b.Append("\n## Rules by path\n\nRead each of these rules before working on the files it is for:\n\n");
			foreach (var rule in byPath)
				b.Append($"- `{ClaudeRule(rule.Name)}`: ").Append(string.Join(", ", rule.Paths.Select(p => $"`{p}`"))).Append('\n');
		}
		return b.ToString();
	}

	/// <summary><c>CLAUDE.md</c> (proposal 5): Claude reads what the other agents read.</summary>
	public static string Claude(string from) => FxHeader.Xml(from) + "\n@AGENTS.md\n";

	/// <summary>Where a rule by path goes for Claude, relative to the root.</summary>
	public static string ClaudeRule(string name) => $"{HarnessModule.ClaudeRules}/{name}.md";

	/// <summary>A rule by path for Claude: its <c>paths</c> in the front matter, then the header and the rule.</summary>
	public static string PathRule(HarnessRule rule, string text, string from)
	{
		var b = new StringBuilder("---\npaths:\n");
		foreach (var path in rule.Paths)
			b.Append("  - ").Append(YamlEditor.Quote(path)).Append('\n');
		b.Append("---\n\n").Append(FxHeader.Xml(from)).Append('\n').Append(Body(text));
		return b.ToString();
	}

	/// <summary>
	/// The <c>SKILL.md</c> of a skill as it is generated (proposal 6): its front matter, the header and its body; null if it
	/// has no front matter.
	/// </summary>
	public static string? Skill(string text, string from)
	{
		if (FrontMatter(text) is not { } parts)
			return null;
		return parts.FrontMatter + "\n" + FxHeader.Xml(from) + "\n" + Body(parts.Body);
	}

	/// <summary>The front matter of a Markdown file (with its <c>---</c> lines) and the rest; null if it has none.</summary>
	public static (string FrontMatter, string Yaml, string Body)? FrontMatter(string text)
	{
		var lines = text.Replace("\r\n", "\n").Split('\n');
		if (lines.Length < 2 || lines[0].TrimEnd() != "---")
			return null;
		var end = Array.FindIndex(lines, 1, l => l.TrimEnd() == "---");
		if (end < 0)
			return null;
		return (string.Join('\n', lines[..(end + 1)]) + "\n", string.Join('\n', lines[1..end]), string.Join('\n', lines[(end + 1)..]));
	}

	/// <summary>The text of a rule or a skill: without the blank lines around it, ending in one '\n'.</summary>
	static string Body(string text) => text.Replace("\r\n", "\n").Trim('\n') + "\n";
}
